"""Generate bounded public MC/WC history and verify it against pinned native TOS.

These fixed public test seeds are never operational keys. Native signatures use
normal randomized signing; retain the generated bytes and their receipt.
"""

import argparse
import base64
import copy
import hashlib
import json
import subprocess
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--cpp-build", type=Path, required=True)
parser.add_argument("--out", type=Path, required=True)
parser.add_argument("--target-dir", type=Path)
args = parser.parse_args()
repo = Path(__file__).resolve().parents[2]
root = args.out.resolve()
if root.exists() and any(root.iterdir()):
    raise SystemExit("output directory must be empty to preserve previous receipts")
root.mkdir(parents=True, exist_ok=True)
with (root / "native-build.log").open("w") as log:
    subprocess.run(
        [
            "python3",
            str(Path(__file__).with_name("publication_fixture_reference.py")),
            "--cpp-build",
            str(args.cpp_build.resolve()),
            "--out",
            str(root / "native"),
        ],
        cwd=repo,
        stdout=log,
        stderr=subprocess.STDOUT,
        check=True,
    )
probe = root / "native/probe"
reference = args.cpp_build.resolve() / "test/conformance/conformance-ref-cli"
keys = [
    line.split()[2]
    for line in (root / "native/native.log").read_text().splitlines()
    if line.startswith("KEY ")
]
assert len(keys) == 3 and all(len(bytes.fromhex(key)) == 1312 for key in keys)
(root / "native-keys.json").write_text(json.dumps(keys) + "\n")
command = ["cargo", "run", "--locked", "-j32", "--release"]
if args.target_dir:
    command += ["--target-dir", str(args.target_dir.resolve())]
command += [
    "-p",
    "rtos_api",
    "--example",
    "node_recovery_fixture",
    "--",
    "--gc-history-keys",
    str(root / "native-keys.json"),
]
with (
    (root / "build.log").open("w") as log,
    (root / "unsigned.json").open("w") as output,
):
    subprocess.run(command, cwd=repo, stdout=output, stderr=log, check=True)
info = json.loads(subprocess.check_output([str(reference), "--info"], text=True))
assert (
    info["reference_commit"]
    == (Path(__file__).with_name("REFERENCE")).read_text().strip()
    and not info["dirty"]
)
data = json.loads((root / "unsigned.json").read_text())
assert len(data["cases"]) == 4
key_controls = []
key_bytes = (root / "native-keys.json").read_bytes()
for label, payload, expected, diagnostic in [
    ("at-limit", key_bytes + b" " * ((16 << 10) - len(key_bytes)), 0, ""),
    (
        "over-limit",
        key_bytes + b" " * ((16 << 10) + 1 - len(key_bytes)),
        101,
        "GC public-key file exceeds 16KiB",
    ),
    (
        "wrong-key-size",
        json.dumps(["00" * 1311] * 3).encode(),
        101,
        "ML-DSA-44 public keys must be 1312 bytes",
    ),
]:
    path = root / ("keys-" + label + ".json")
    path.write_bytes(payload)
    control_command = command.copy()
    control_command[-1] = str(path)
    result = subprocess.run(
        control_command,
        cwd=repo,
        text=True,
        capture_output=True,
        timeout=60,
        check=False,
    )
    (root / ("keys-" + label + ".log")).write_text(result.stdout + result.stderr)
    assert result.returncode == expected and diagnostic in result.stderr
    if expected == 0:
        assert json.loads(result.stdout) == data
    key_controls.append(
        {"name": label, "exit": result.returncode, "bytes": len(payload)}
    )
contexts = []
previous_state = data["zerostate"]
previous_block = "00"
for index, row in enumerate(data["cases"]):
    for wc in [False, True]:
        prefix = "wc_" if wc else ""
        contexts.append(
            {
                "state": previous_state,
                "block": row[prefix + "block_boc"],
                "candidate": row[prefix + "candidate"],
                "slot": row["slot"],
                "governing": previous_block if wc else "00",
                "prefix": prefix,
                "index": index,
            }
        )
    previous_state = row["state_boc"]
    previous_block = row["block_boc"]


def command_line(context):
    return f"{context['state']} {context['block']} {context['candidate']} {context['slot']} {context['governing']}\n"


request = "".join(command_line(context) for context in contexts)
(root / "context-check-input.txt").write_text(request)
checked = subprocess.run(
    [str(probe), "--check-history"],
    input=request,
    text=True,
    capture_output=True,
    timeout=60,
    check=False,
)
(root / "context-check-output.txt").write_text(checked.stdout)
(root / "context-check-error.txt").write_text(checked.stderr)
assert checked.returncode == 0, (
    "native context checker",
    checked.returncode,
    checked.stderr[:500],
)
lines = checked.stdout.splitlines()
assert len(lines) == len(contexts) == 8
for context, line in zip(contexts, lines, strict=True):
    fields = line.split()
    row = data["cases"][context["index"]]
    prefix = context["prefix"]
    candidate = bytes.fromhex(context["candidate"])
    assert fields[0] == "CHECK" and len(fields) == 9
    assert fields[1].lower() == row[prefix + "session"].lower()
    assert int(fields[2]) == int(fields[3]) == row[prefix + "subset_hash"]
    assert fields[4].lower() == candidate[20:52].hex()
    assert (
        fields[5].lower()
        == hashlib.sha256(bytes.fromhex(context["block"])).hexdigest()
        == candidate[52:84].hex()
    )
    assert fields[6].lower() == row[prefix + "preimage"].lower()

controls = []
for label, index, field, value, expected in [
    ("mc-wrong-state", 2, "state", data["zerostate"], 23),
    ("wc-wrong-governing-block", 3, "governing", data["cases"][1]["block_boc"], 21),
    ("wc-wrong-governing-state", 3, "state", data["zerostate"], 22),
    ("candidate-wrong-block", 2, "candidate", contexts[0]["candidate"], 19),
]:
    changed = copy.deepcopy(contexts[index])
    changed[field] = value
    result = subprocess.run(
        [str(probe), "--check-history"],
        input=command_line(changed),
        text=True,
        capture_output=True,
        timeout=30,
        check=False,
    )
    (root / (label + ".input.txt")).write_text(command_line(changed))
    (root / (label + ".output.txt")).write_text(result.stdout + result.stderr)
    controls.append({"name": label, "expected": expected, "exit": result.returncode})
    assert result.returncode == expected, controls[-1]

oversized = copy.deepcopy(contexts[0])
oversized["governing"] = "f" * ((2 << 20) + 1)
oversized_input = command_line(oversized)
result = subprocess.run(
    [str(probe), "--check-history"],
    input=oversized_input,
    text=True,
    capture_output=True,
    timeout=30,
    check=False,
)
(root / "oversized-governing-input.txt").write_text(oversized_input)
(root / "oversized-governing-output.txt").write_text(result.stdout + result.stderr)
assert result.returncode == 3 and "token too large" in result.stderr
controls.append(
    {"name": "oversized-governing", "expected": 3, "exit": result.returncode}
)

# Keep the original four-token publication checker contract exercised too.
legacy = json.loads(
    (
        repo / "rtos/src/full_node/finality/testdata/v2-publication-spool.json"
    ).read_text()
)
legacy_request = "".join(
    f"{legacy['state_boc']} {row['block_boc']} {row['candidate']} {row['slot']}\n"
    for row in legacy["rows"]
)
legacy_check = subprocess.run(
    [str(probe), "--check"],
    input=legacy_request,
    text=True,
    capture_output=True,
    timeout=30,
    check=True,
)
(root / "legacy-context-input.txt").write_text(legacy_request)
(root / "legacy-context-output.txt").write_text(legacy_check.stdout)
legacy_lines = legacy_check.stdout.splitlines()
assert len(legacy_lines) == len(legacy["rows"]) == 2
for row, line in zip(legacy["rows"], legacy_lines, strict=True):
    fields = line.split()
    assert fields[1].lower() == row["session"].lower()
    assert fields[6].lower() == row["preimage"].lower()

signing = "".join(
    f"{member} {data['cases'][context['index']][context['prefix'] + 'preimage']}\n"
    for context in contexts
    for member in range(3)
)
(root / "signing-input.txt").write_text(signing)
signed = subprocess.run(
    [str(probe)], input=signing, text=True, capture_output=True, timeout=60, check=True
)
(root / "signing-output.txt").write_text(signed.stdout)
rows = [line.split() for line in signed.stdout.splitlines()]
assert [value for kind, _, value in rows if kind == "KEY"] == keys
signatures = [
    (int(member), value) for kind, member, value in rows if kind == "SIGNATURE"
]
assert len(signatures) == 24
crypto = []
offset = 0
for context in contexts:
    row = data["cases"][context["index"]]
    prefix = context["prefix"]
    records = []
    for member in range(3):
        index, signature = signatures[offset]
        offset += 1
        assert index == member and len(bytes.fromhex(signature)) == 2420
        records.append(
            {
                "index": member,
                "validator_id": (member + 1).to_bytes(4, "little").hex() + "00" * 28,
                "signature": signature,
            }
        )
        crypto.append(
            {
                "scheme": "mldsa44",
                "operation": "verify",
                "inputs": {
                    key: base64.b64encode(value).decode()
                    for key, value in {
                        "message": bytes.fromhex(row[prefix + "preimage"]),
                        "context": b"TOS-CONSENSUS-SIMPLEX-v1",
                        "public_key": bytes.fromhex(keys[member]),
                        "signature": bytes.fromhex(signature),
                    }.items()
                },
            }
        )
    row[prefix + "signatures"] = records
for field in ["message", "context"]:
    negative = copy.deepcopy(crypto[0])
    negative["inputs"][field] = base64.b64encode(
        base64.b64decode(negative["inputs"][field]) + b"!"
    ).decode()
    crypto.append(negative)
request = "".join(json.dumps(row) + "\n" for row in crypto)
(root / "crypto-input.jsonl").write_text(request)
verified = subprocess.run(
    [str(reference), "crypto"],
    input=request,
    text=True,
    capture_output=True,
    timeout=60,
    check=True,
)
(root / "crypto-output.jsonl").write_text(verified.stdout)
effects = [json.loads(line) for line in verified.stdout.splitlines()]
assert len(effects) == 26
assert all(
    effect == {"outcome": "verdict", "verdict": "valid"} for effect in effects[:24]
)
assert all(
    effect == {"outcome": "verdict", "verdict": "invalid"} for effect in effects[24:]
)
data["reference_commit"] = info["reference_commit"]
data["native_gc_history"] = True
data["qualification"] = (
    "Public synthetic MC/WC4-height history. Native state/header context and24 MLDSA final signatures checked; not whole block transaction execution, actual node GC, cold boot, power-loss or soak qualification."
)
(root / "signed.json").write_text(json.dumps(data, indent=2) + "\n")
receipt = {
    "reference_info": info,
    "contexts": 8,
    "signatures": 24,
    "wrong_message_and_domain": 2,
    "context_controls": controls,
    "legacy_publication_contexts": len(legacy_lines),
    "key_input_controls": key_controls,
    "artifacts": [],
}
for name in [
    "native/probe",
    "context-check-input.txt",
    "context-check-output.txt",
    "signing-input.txt",
    "signing-output.txt",
    "crypto-input.jsonl",
    "crypto-output.jsonl",
    "signed.json",
]:
    path = root / name
    receipt["artifacts"].append(
        {
            "path": str(path),
            "bytes": path.stat().st_size,
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        }
    )
for path in [
    Path(__file__),
    Path(__file__).with_name("publication_fixture_reference.cpp"),
    repo / "tl/rtos_api/examples/node_recovery_fixture.rs",
]:
    receipt["artifacts"].append(
        {
            "path": str(path),
            "bytes": path.stat().st_size,
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        }
    )
(root / "native-history-receipt.json").write_text(json.dumps(receipt, indent=2) + "\n")
print(
    "8 native contexts and24 signatures match;4 context mutations and2 cryptographic mutations refuse. Runtime/GC integration not yet performed."
)
